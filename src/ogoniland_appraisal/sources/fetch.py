"""Download the documents listed in the source seed and record a sha256 manifest.

Files are written to ``data/raw/`` exactly as served: never renamed, repaired,
converted or truncated. A download is validated (starts with ``%PDF``, at
least 10 KB) before it is moved into place; any violation stops the run.
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import json
import os
import sys
import time
from pathlib import Path

import requests

from .discover import USER_AGENT as _DISCOVER_UA, _read_seed

USER_AGENT = _DISCOVER_UA.replace("source-discovery", "source-fetch")
SLEEP_SECONDS = 1.0
MIN_BYTES = 10 * 1024
MAX_RETRIES = 2
BACKOFF_SECONDS = 2.0
TRANSIENT_STATUS = (429, 500, 502, 503, 504)

DUPLICATE_PAIRS = [
    ("factsheet_09", "factsheet_26", "008-010"),
    ("factsheet_25", "factsheet_45", "005-002"),
    ("factsheet_12", "factsheet_48", "010-009"),
    ("factsheet_60", "factsheet_67", "008-003"),
]

DEFAULT_SEED = "docs/sources_seed.yml"
DEFAULT_RAW = "data/raw"
DEFAULT_MANIFEST = "docs/sources_manifest.json"
SOURCES_MD = "SOURCES.md"


class FetchStop(RuntimeError):
    """A spec stop rule fired; the message says which."""


def _now():
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _load_manifest(path):
    path = Path(path)
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {d["doc_id"]: d for d in data["documents"]}


def _write_manifest(path, docs):
    docs = sorted(docs, key=lambda d: d["doc_id"])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({"generated_utc": _now(), "documents": docs}, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return docs


def _write_sources_md(path, docs, generated):
    def cell(v):
        return str(v).replace("|", "\\|")

    out = [
        "# Sources",
        "",
        f"Generated by `ogoniland_appraisal.sources.fetch` on {generated} (UTC); "
        f"{len(docs)} documents. Do not edit by hand.",
        "",
        f"The UNEP repository is a live system; this manifest is a snapshot as at {generated} (UTC).",
        "",
        "| doc_id | title | year | url | sha256 (first 16) | local_filename | bytes |",
        "|---|---|---|---|---|---|---|",
    ]
    for d in docs:
        out.append("| " + " | ".join([
            cell(d["doc_id"]), cell(d["title"]), "" if d["year"] is None else str(d["year"]),
            cell(d["url"]), d["sha256"][:16], cell(d["local_filename"]), str(d["bytes"]),
        ]) + " |")
    regs = [d for d in docs if d.get("kind") == "regulation"]
    if regs:
        out += ["", "## Regulatory sources", ""]
        for d in regs:
            out.append(f"- **{d['doc_id']}** ({d['year']}): {d['title']}. {d['provenance_note']}")
        manual_ids = ", ".join(d["doc_id"] for d in docs if d.get("retrieval_method") == "manual")
        out += ["", f"Manually retrieved (not fetched by script): {manual_ids}."]
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


class _Downloader:
    def __init__(self):
        self.s = requests.Session()
        self.s.headers.update({"User-Agent": USER_AGENT})
        self._last = 0.0
        self.retries = []

    def download(self, url, dest_part, label):
        """Stream url to dest_part. Retries transient failures; stops otherwise."""
        for attempt in range(MAX_RETRIES + 1):
            wait = SLEEP_SECONDS - (time.monotonic() - self._last)
            if wait > 0:
                time.sleep(wait)
            try:
                with self.s.get(url, stream=True, timeout=(30, 120)) as r:
                    self._last = time.monotonic()
                    if r.status_code == 200:
                        with open(dest_part, "wb") as fh:
                            for chunk in r.iter_content(1 << 16):
                                fh.write(chunk)
                        return
                    reason = f"HTTP {r.status_code}"
                    transient = r.status_code in TRANSIENT_STATUS
            except (requests.ConnectionError, requests.Timeout) as exc:
                self._last = time.monotonic()
                reason, transient = type(exc).__name__, True
            if not transient or attempt == MAX_RETRIES:
                raise FetchStop(f"{label}: {reason} for {url} after {attempt} retries")
            delay = BACKOFF_SECONDS * (2 ** attempt)
            self.retries.append(f"{label}: {reason}; retry {attempt + 1} in {delay:.0f}s")
            time.sleep(delay)


def duplicate_pair_report(docs):
    by_id = {d["doc_id"]: d for d in docs}
    rows = []
    for a, b, code in DUPLICATE_PAIRS:
        if a not in by_id or b not in by_id:
            rows.append({"pair": [a, b], "site": code, "result": "not in manifest"})
            continue
        same = by_id[a]["sha256"] == by_id[b]["sha256"]
        rows.append({"pair": [a, b], "site": code,
                     "result": "identical" if same else "differing",
                     "sha256_first16": [by_id[a]["sha256"][:16], by_id[b]["sha256"][:16]]})
    return rows


def _register_manual(e, dest, prior):
    """Hash a manually retrieved file already in raw_dir; never download or touch it."""
    if not dest.is_file():
        raise FetchStop(f"{e['doc_id']}: manually retrieved file missing: {dest}")
    with open(dest, "rb") as fh:
        head = fh.read(4)
    if head != b"%PDF":
        raise FetchStop(f"{e['doc_id']}: file does not begin with %PDF (got {head!r})")
    size = dest.stat().st_size
    if size < MIN_BYTES:
        raise FetchStop(f"{e['doc_id']}: file is {size} bytes, under 10 KB")
    digest = _sha256(dest)
    if prior and prior["sha256"] != digest:
        raise FetchStop(f"{e['doc_id']}: {dest} sha256 differs from manifest")
    # retrieved_utc carries the date given for the manual retrieval (no time is known).
    return {**e, "sha256": digest, "bytes": size, "retrieved_utc": e["retrieved_date"]}


def fetch_all(seed_path, raw_dir, manifest_path) -> dict:
    seed = _read_seed(Path(seed_path))
    raw = Path(raw_dir)
    raw.mkdir(parents=True, exist_ok=True)
    names = [e["local_filename"] for e in seed]
    dups = sorted({n for n in names if names.count(n) > 1})
    if dups:
        raise FetchStop(f"seed entries share a local_filename: {dups}")

    existing = _load_manifest(manifest_path)
    dl = _Downloader()
    docs, downloaded, skipped, manual, bytes_dl = {}, [], [], [], 0

    for e in sorted(seed, key=lambda e: e["doc_id"]):
        dest = raw / e["local_filename"]
        prior = existing.get(e["doc_id"])
        if e.get("retrieval_method") == "manual":
            # Manually retrieved: never downloaded here, only hashed in place.
            docs[e["doc_id"]] = _register_manual(e, dest, prior)
            manual.append(e["doc_id"])
            continue
        if dest.is_file() and prior:
            if _sha256(dest) != prior["sha256"]:
                raise FetchStop(f"{e['doc_id']}: {dest} sha256 differs from manifest")
            docs[e["doc_id"]] = prior
            skipped.append(e["doc_id"])
            continue
        part = raw / (e["local_filename"] + ".part")
        try:
            dl.download(e["url"], part, e["doc_id"])
            size = part.stat().st_size
            with open(part, "rb") as fh:
                head = fh.read(4)
            if head != b"%PDF":
                raise FetchStop(f"{e['doc_id']}: file does not begin with %PDF (got {head!r})")
            if size < MIN_BYTES:
                raise FetchStop(f"{e['doc_id']}: file is {size} bytes, under 10 KB")
            digest = _sha256(part)
            os.replace(part, dest)
        finally:
            if part.exists():
                part.unlink()
        docs[e["doc_id"]] = {**e, "sha256": digest, "bytes": size, "retrieved_utc": _now()}
        downloaded.append(e["doc_id"])
        bytes_dl += size
        _write_manifest(manifest_path, list(docs.values()))  # incremental, resumable

    final = _write_manifest(manifest_path, list(docs.values()))
    generated = _now()
    _write_sources_md(Path(manifest_path).parent / SOURCES_MD, final, generated)
    return {"n_documents": len(final), "downloaded": len(downloaded), "skipped": len(skipped), "manual": len(manual),
            "bytes_downloaded": bytes_dl, "retries": dl.retries,
            "duplicate_pairs": duplicate_pair_report(final)}


def verify(raw_dir, manifest_path) -> dict:
    ok, missing, mismatched = [], [], []
    for d in _load_manifest(manifest_path).values():
        p = Path(raw_dir) / d["local_filename"]
        if not p.is_file():
            missing.append(d["doc_id"])
        elif _sha256(p) != d["sha256"] or p.stat().st_size != d["bytes"]:
            mismatched.append(d["doc_id"])
        else:
            ok.append(d["doc_id"])
    return {"ok": ok, "missing": missing, "mismatched": mismatched}


if __name__ == "__main__":
    try:
        summary = fetch_all(DEFAULT_SEED, DEFAULT_RAW, DEFAULT_MANIFEST)
    except FetchStop as exc:
        print(f"STOP: {exc}", file=sys.stderr)
        sys.exit(2)
    print(json.dumps(summary, indent=2))
    v = verify(DEFAULT_RAW, DEFAULT_MANIFEST)
    print(json.dumps({"ok": len(v["ok"]), "missing": v["missing"], "mismatched": v["mismatched"]},
                     indent=2))
